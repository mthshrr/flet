CREATE TABLE IF NOT EXISTS tarefas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome TEXT NOT NULL,
    tipo TEXT NOT NULL DEFAULT 'Comum',
    xp INT NOT NULL DEFAULT 10,
    concluida BOOLEAN NOT NULL DEFAULT FALSE,
    criado_em TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- Habilitar Row Level Security (RLS) opcional ou liberar acesso para a chave pública anon:
ALTER TABLE tarefas ENABLE ROW LEVEL SECURITY;

-- Política simples para permitir leitura, inserção, atualização e exclusão na chave anon
CREATE POLICY "Permitir acesso completo a tarefas" ON tarefas
    FOR ALL
    USING (true)
    WITH CHECK (true);
